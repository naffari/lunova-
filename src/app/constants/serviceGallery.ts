/**
 * REAL JOB PHOTOGRAPHY, per department.
 *
 * This is the manifest behind the "What done looks like" section on each
 * service page. It is the difference between the site showing stock imagery and
 * the site showing evidence — so the distinction is encoded, not assumed:
 *
 *   own: true   → Lunova's own completed work. Section is headed as such and
 *                 may claim the result.
 *   own: false  → reference/illustrative imagery. Section says so plainly.
 *
 * Never flip `own` to true for an image you did not shoot on a Lunova job. The
 * whole value of this section is that a customer can trust it, and a single
 * reverse-image hit on a stock photo destroys that for every other claim on the
 * page.
 *
 * FILE LOCATIONS — originals go in assets-src/work/<service-key>/ and are NOT
 * deployed. Run `pnpm images` to generate the responsive variants into
 * public/images/work/<service-key>/. The `file` field below is the base name,
 * with no directory, width suffix, or extension.
 */

import { hasWorkPhoto } from "./workManifest";

export interface WorkPhoto {
  /** Base filename, no extension. Variants are generated by `pnpm images`. */
  file: string;
  alt: string;
  /** Optional short caption shown under the photo. */
  caption?: string;
}

export interface BeforeAfterPair {
  before: string;
  after: string;
  beforeAlt: string;
  afterAlt: string;
}

export interface ServiceGallery {
  /** True only for photography shot on Lunova's own jobs. */
  own: boolean;
  heading: string;
  blurb: string;
  photos: WorkPhoto[];
  /** Optional drag-slider pair, for services where the change is the product. */
  beforeAfter?: BeforeAfterPair;
}

