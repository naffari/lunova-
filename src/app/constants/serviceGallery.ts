/**
 * Resolves a department's gallery down to what actually exists on disk.
 *
 * Declarations above are aspirational — a photo can be named here before its
 * file has been dropped into assets-src/work/. This filters against the
 * generated manifest so a missing file hides its photo (and a before/after pair
 * missing either frame drops the whole slider) instead of shipping a broken
 * image. Returns undefined when nothing survives, and WorkGallery renders null.
 */
export function getGallery(serviceKey: string): ServiceGallery | undefined {
  const gallery = SERVICE_GALLERIES[serviceKey];
  if (!gallery) return undefined;

  const photos = gallery.photos.filter((p) => hasWorkPhoto(serviceKey, p.file));

  const pair = gallery.beforeAfter;
  const beforeAfter =
    pair && hasWorkPhoto(serviceKey, pair.before) && hasWorkPhoto(serviceKey, pair.after)
      ? pair
      : undefined;

  if (photos.length === 0 && !beforeAfter) return undefined;

  return { ...gallery, photos, beforeAfter };
}
